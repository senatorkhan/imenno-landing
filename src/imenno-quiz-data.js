  function rank(scenarioKey, {clue, occasion, budget, excluded} = {}) {
    const scenario = Object.hasOwn(scenarios, scenarioKey) ? scenarios[scenarioKey] : null;
    const validClue = scenario?.clues.some(option => option.id === clue);
    const validOccasion = occasion === 'birthday' || occasion === 'attention';
    const priceLimit = Number(budget);

    if (!validClue || !validOccasion || !Number.isFinite(priceLimit) || priceLimit <= 0) {
      return [];
    }

    const alreadyGiven = new Set(Array.isArray(excluded) ? excluded : []);
    const score = gift => gift.fit[clue].score * 2 + gift.occasions[occasion].score;

    return scenario.gifts
      .filter(gift => gift.price <= priceLimit && !alreadyGiven.has(gift.id))
      .sort((a, b) => score(b) - score(a) || a.price - b.price);
  }

  window.imennoQuizDemo = {scenarios, rank};
